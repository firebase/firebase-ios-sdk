import Foundation

/// A type that represents a remote multimodal model (like Gemini), with the ability to generate
/// content based on various input types.
///
/// **Public Preview**: This API is a public preview and may be subject to change.
public final class TemplateGenerativeModel: Sendable {
  let generativeAIService: GenerativeAIService
  let apiConfig: APIConfig

  /// Tool configuration for any `Tool` specified in the request.
  let toolConfig: TemplateToolConfig?

  /// Configuration parameters for sending requests to the backend.
  let requestOptions: RequestOptions

  init(firebaseInfo: FirebaseInfo, apiConfig: APIConfig, toolConfig: TemplateToolConfig?,
       requestOptions: RequestOptions, urlSession: URLSession = GenAIURLSession.default) {
    generativeAIService = GenerativeAIService(
      firebaseInfo: firebaseInfo,
      urlSession: urlSession
    )
    self.apiConfig = apiConfig
    self.toolConfig = toolConfig
    self.requestOptions = requestOptions
  }

  /// Generates content from a prompt template and inputs.
  ///
  /// **Public Preview**: This API is a public preview and may be subject to change.
  ///
  /// - Parameters:
  ///   - templateID: The ID of the prompt template to use.
  ///   - inputs: A dictionary of variables to substitute into the template.
  ///   - options: The ``RequestOptions`` for the request, currently used to override default
  ///     request timeout.
  ///   - toolConfig: The ``TemplateToolConfig`` for the request (for example, if it uses the
  ///     Grounding with Google Maps tool).
  /// - Returns: The content generated by the model.
  /// - Throws: A ``GenerateContentError`` if the request failed.
  public func generateContent(templateID: String,
                              inputs: [String: Any]) async throws -> GenerateContentResponse {
    return try await generateContentWithHistory(history: [], template: templateID, inputs: inputs)
  }

  /// Generates content from a prompt template and inputs, with streaming responses.
  ///
  /// **Public Preview**: This API is a public preview and may be subject to change.
  ///
  /// - Parameters:
  ///   - templateID: The ID of the prompt template to use.
  ///   - inputs: A dictionary of variables to substitute into the template.
  ///   - options: The ``RequestOptions`` for the request, currently used to override default
  ///     request timeout.
  ///   - toolConfig: The ``TemplateToolConfig`` for the request (for example, if it uses the
  ///     Grounding with Google Maps tool).
  /// - Returns: An `AsyncThrowingStream` that yields `GenerateContentResponse` objects.
  /// - Throws: A ``GenerateContentError`` if the request failed.
  @available(macOS 12.0, watchOS 8.0, *)
  public func generateContentStream(templateID: String, inputs: [String: Any]) throws
    -> AsyncThrowingStream<GenerateContentResponse, Error> {
    return try generateContentStreamWithHistory(history: [], template: templateID, inputs: inputs)
  }

  // TODO: Restore `public` determined to be releaseable along with the contents of TemplateChatSession.

  /// Creates a new chat conversation using this model with the provided history and template.
  ///
  /// - Parameters:
  ///   - templateID: The ID of the prompt template to use.
  ///   - history: The conversation history to use.
  /// - Returns: A new ``TemplateChatSession`` instance.
  func startChat(templateID: String,
                 inputs: [String: Any],
                 history: [ModelContent] = []) -> TemplateChatSession {
    return TemplateChatSession(
      model: self,
      templateID: templateID,
      inputs: inputs,
      history: history
    )
  }

  // MARK: - Internal

  func templateGenerateContentRequest(template: String, inputs: [String: Any],
                                      history: [ModelContent],
                                      stream: Bool) throws -> TemplateGenerateContentRequest {
    return try TemplateGenerateContentRequest(
      template: template,
      inputs: inputs.mapValues { try TemplateInput(value: $0) },
      history: history,
      projectID: generativeAIService.firebaseInfo.projectID,
      stream: false,
      apiConfig: apiConfig,
      options: requestOptions,
      toolConfig: toolConfig
    )
  }

  /// Generates content from a prompt template, inputs, and history.
  ///
  /// - Parameters:
  ///   - history: The conversation history to use.
  ///   - template: The prompt template to use.
  ///   - inputs: A dictionary of variables to substitute into the template.
  ///   - options: The ``RequestOptions`` for the request.
  ///   - toolConfig: The ``TemplateToolConfig`` for the request (for example, if it uses the
  ///     Grounding with Google Maps tool).
  /// - Returns: The content generated by the model.
  /// - Throws: A ``GenerateContentError`` if the request failed.
  func generateContentWithHistory(history: [ModelContent], template: String,
                                  inputs: [String: Any]) async throws -> GenerateContentResponse {
    let request = try templateGenerateContentRequest(
      template: template,
      inputs: inputs,
      history: history,
      stream: false
    )

    return try await generativeAIService.loadRequest(request: request)
  }

  /// Generates a stream of content from a prompt template, inputs, and history.
  ///
  /// - Parameters:
  ///   - history: The conversation history to use.
  ///   - template: The prompt template to use.
  ///   - inputs: A dictionary of variables to substitute into the template.
  ///   - options: The ``RequestOptions`` for the request.
  ///   - toolConfig: The ``TemplateToolConfig`` for the request (for example, if it uses the
  ///     Grounding with Google Maps tool).
  /// - Returns: An `AsyncThrowingStream` that yields `GenerateContentResponse` objects.
  /// - Throws: A ``GenerateContentError`` if the request failed.
  @available(macOS 12.0, watchOS 8.0, *)
  func generateContentStreamWithHistory(history: [ModelContent], template: String,
                                        inputs: [String: Any]) throws
    -> AsyncThrowingStream<GenerateContentResponse, Error> {
    let request = try templateGenerateContentRequest(
      template: template,
      inputs: inputs,
      history: history,
      stream: true
    )

    return generativeAIService.loadRequestStream(request: request)
  }
}
