#if compiler(>=6.4)
  extension LanguageModelSession {
    /// A completed response generated by a language model session.
    ///
    /// - SeeAlso: [`LanguageModelSession.Response`](https://developer.apple.com/documentation/foundationmodels/languagemodelsession/response)
    public struct Response<Content> where Content: Generable {
      /// The typed content generated by the model.
      public let content: Content

      /// The raw generated content returned by the model.
      public let rawContent: GeneratedContent

      /// The slice of transcript entries produced during the response.
      public let transcriptEntries: ArraySlice<Transcript.Entry>

      /// The token usage statistics for generating the response.
      @available(iOS 27.0, macOS 27.0, visionOS 27.0, watchOS 27.0, *)
      @available(tvOS, unavailable)
      public let usage: LanguageModelSession.Usage
    }
  }

  @available(tvOS, unavailable)
  extension LanguageModelSession.Response: Sendable where Content: Sendable {
  }

  extension LanguageModelSession {
    /// Token usage metrics for language model requests.
    ///
    /// - SeeAlso: [`LanguageModelSession.Usage`](https://developer.apple.com/documentation/foundationmodels/languagemodelsession/usage)
    @available(iOS 27.0, macOS 27.0, visionOS 27.0, watchOS 27.0, *)
    @available(tvOS, unavailable)
    public struct Usage: Sendable {
      /// The token counts consumed by input processing.
      public var input: LanguageModelSession.Usage.Input

      /// The token counts produced during output generation.
      public var output: LanguageModelSession.Usage.Output

      /// Additional model-specific metadata associated with the usage.
      public var metadata: [String: GeneratedContent]

      /// Creates a usage instance with the specified input, output, and metadata.
      ///
      /// - Parameters:
      ///   - input: The input token usage.
      ///   - output: The output token usage.
      ///   - metadata: Additional usage metadata.
      public init(
        input: LanguageModelSession.Usage.Input,
        output: LanguageModelSession.Usage.Output,
        metadata: [String: any ConvertibleToGeneratedContent] = [:]
      ) {
        self.input = input
        self.output = output
        self.metadata = metadata.mapValues(\.generatedContent)
      }
    }
  }

  extension LanguageModelSession.Usage {
    /// Token usage breakdown for prompt and input processing.
    ///
    /// - SeeAlso: [`LanguageModelSession.Usage.Input`](https://developer.apple.com/documentation/foundationmodels/languagemodelsession/usage/input)
    public struct Input: Sendable {
      /// The total number of input tokens processed.
      public var totalTokenCount: Int

      /// The number of input tokens retrieved from cache.
      public var cachedTokenCount: Int

      /// Creates an input token usage record.
      ///
      /// - Parameters:
      ///   - totalTokenCount: The total number of input tokens.
      ///   - cachedTokenCount: The number of cached input tokens.
      public init(totalTokenCount: Int, cachedTokenCount: Int) {
        self.totalTokenCount = totalTokenCount
        self.cachedTokenCount = cachedTokenCount
      }
    }
  }

  extension LanguageModelSession.Usage {
    /// Token usage breakdown for generated output.
    ///
    /// - SeeAlso: [`LanguageModelSession.Usage.Output`](https://developer.apple.com/documentation/foundationmodels/languagemodelsession/usage/output)
    public struct Output: Sendable {
      /// The total number of output tokens generated.
      public var totalTokenCount: Int

      /// The number of reasoning tokens generated.
      public var reasoningTokenCount: Int

      /// Creates an output token usage record.
      ///
      /// - Parameters:
      ///   - totalTokenCount: The total number of output tokens.
      ///   - reasoningTokenCount: The number of reasoning tokens.
      public init(totalTokenCount: Int, reasoningTokenCount: Int) {
        self.totalTokenCount = totalTokenCount
        self.reasoningTokenCount = reasoningTokenCount
      }
    }
  }

  extension LanguageModelSession.Usage {
    /// The combined total number of input and output tokens.
    public var totalTokenCount: Int {
      input.totalTokenCount + output.totalTokenCount
    }

    /// A usage value with zeroed input and output token counts and empty metadata.
    internal static var zero: Self {
      Self(
        input: Input(totalTokenCount: 0, cachedTokenCount: 0),
        output: Output(totalTokenCount: 0, reasoningTokenCount: 0),
        metadata: [:]
      )
    }
  }
#endif  // compiler(>=6.4)
