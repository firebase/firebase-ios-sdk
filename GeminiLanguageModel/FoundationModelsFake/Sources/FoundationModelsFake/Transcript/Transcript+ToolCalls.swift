    public typealias Element = Transcript.ToolCall

    /// The index type for a tool calls collection.
    public typealias Index = Int

    /// A type representing valid indices into a tool calls collection.
    public typealias Indices = Range<Int>

    /// An iterator over the tool calls in the collection.
    public typealias Iterator = IndexingIterator<Transcript.ToolCalls>

    /// A slice of a tool calls collection.
    public typealias SubSequence = Slice<Transcript.ToolCalls>
  }

  extension Transcript {
    /// A call to a specific tool requested by the model.
    ///
    /// - SeeAlso: [`Transcript.ToolCall`](https://developer.apple.com/documentation/foundationmodels/transcript/toolcall)
    public struct ToolCall: Sendable, Identifiable, Equatable {
      /// The unique identifier of the tool call.
      public var id: String

      /// The name of the tool to be called.
      public var toolName: String

      /// The arguments generated by the model for the tool call.
      public var arguments: GeneratedContent {
        get {
          storedArguments
        }
        set {
          storedArguments = newValue
          rawArguments = nil
        }
      }

      /// The storage that backs ``arguments``.
      var storedArguments: GeneratedContent

      /// The arguments' JSON text as read from a serialized transcript, if any.
      ///
      /// Keeping the original argument text means a decoded transcript re-encodes and describes
      /// its arguments exactly as they were written, even though the decoded ``arguments`` lose
      /// their key order. Setting ``arguments`` clears it.
      var rawArguments: String?

      /// The JSON text that represents the arguments in descriptions and serialized transcripts.
      var argumentsJSONString: String {
        rawArguments ?? storedArguments.jsonString
      }

      /// Additional metadata associated with the tool call.
      @available(iOS 27.0, macOS 27.0, visionOS 27.0, watchOS 27.0, *)
      @available(tvOS, unavailable)
      public var metadata: [String: GeneratedContent]

      /// The identifier type for a tool call.
      public typealias ID = String
    }
  }

  extension Transcript.ToolCall {
    /// Creates a tool call with an identifier, tool name, and arguments.
    ///
    /// - Parameters:
    ///   - id: The unique identifier for the tool call.
    ///   - toolName: The name of the tool being called.
    ///   - arguments: The arguments supplied for the tool call.
    public init(id: String, toolName: String, arguments: GeneratedContent) {
      self.init(id: id, metadata: [:], toolName: toolName, arguments: arguments)
    }

    /// Creates a tool call with an identifier, metadata, tool name, and arguments.
    ///
    /// - Parameters:
    ///   - id: The unique identifier for the tool call.
    ///   - metadata: Metadata associated with the tool call.
    ///   - toolName: The name of the tool being called.
    ///   - arguments: The arguments supplied for the tool call.
    @available(iOS 27.0, macOS 27.0, visionOS 27.0, watchOS 27.0, *)
    @available(tvOS, unavailable)
    public init(
      id: String,
      metadata: [String: any ConvertibleToGeneratedContent],
      toolName: String,
      arguments: GeneratedContent
    ) {
      self.id = id
      self.metadata = metadata.mapValues(\.generatedContent)
      self.toolName = toolName
      self.storedArguments = arguments
      self.rawArguments = nil
    }

    /// Returns a Boolean value indicating whether two tool calls are equal.
    ///
    /// - Parameters:
    ///   - lhs: The first tool call to compare.
    ///   - rhs: The second tool call to compare.
    /// - Returns: `true` if both tool calls are equal.
    public static func == (lhs: Transcript.ToolCall, rhs: Transcript.ToolCall) -> Bool {
      lhs.id == rhs.id
        && lhs.toolName == rhs.toolName
        && lhs.storedArguments == rhs.storedArguments
        && lhs.metadata == rhs.metadata
    }
  }

  extension Transcript {
    /// The output produced by running a tool.
    ///
    /// - SeeAlso: [`Transcript.ToolOutput`](https://developer.apple.com/documentation/foundationmodels/transcript/tooloutput)
    public struct ToolOutput: Sendable, Identifiable, Equatable {
      /// The unique identifier of the tool output.
      public var id: String

      /// The name of the tool that produced this output.
      public var toolName: String

      /// The segments containing the content of the tool output.
      public var segments: [Transcript.Segment]

      /// Creates a tool output record.
      ///
      /// - Parameters:
      ///   - id: The unique identifier for the tool output.
      ///   - toolName: The name of the tool that generated this output.
      ///   - segments: The segments representing the tool output content.
      public init(id: String, toolName: String, segments: [Transcript.Segment]) {
        self.id = id
        self.toolName = toolName
        self.segments = segments
      }

      /// Returns a Boolean value indicating whether two tool outputs are equal.
      ///
      /// - Parameters:
      ///   - a: The first tool output to compare.
      ///   - b: The second tool output to compare.
      /// - Returns: `true` if both tool outputs are equal.
      public static func == (a: Transcript.ToolOutput, b: Transcript.ToolOutput) -> Bool {
        a.id == b.id && a.toolName == b.toolName && a.segments == b.segments
      }

      /// The identifier type for a tool output.
      public typealias ID = String
    }
  }
