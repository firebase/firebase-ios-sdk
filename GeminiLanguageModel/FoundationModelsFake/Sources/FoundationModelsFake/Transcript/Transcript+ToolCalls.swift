  extension Transcript {
    /// A collection of tool calls requested by a model.
    ///
    /// - SeeAlso: [`Transcript.ToolCalls`](https://developer.apple.com/documentation/foundationmodels/transcript/toolcalls)
    public struct ToolCalls: Sendable, Identifiable, Equatable {
      /// The unique identifier of the tool calls collection.
      public var id: String

      /// The tool calls, in the order the model generated them.
      var calls: [Transcript.ToolCall]

      /// Creates a collection of tool calls from a sequence.
      ///
      /// - Parameters:
      ///   - id: The unique identifier for the tool calls.
      ///   - calls: The sequence of tool calls.
      public init<S>(
        id: String = UUID().uuidString,
        _ calls: S
      ) where S: Sequence, S.Element == Transcript.ToolCall {
        self.id = id
        self.calls = Array(calls)
      }

      /// Returns a Boolean value indicating whether two tool call collections are equal.
      ///
      /// - Parameters:
      ///   - a: The first tool call collection to compare.
      ///   - b: The second tool call collection to compare.
      /// - Returns: `true` if both collections have equal identifiers and tool calls.
      public static func == (a: Transcript.ToolCalls, b: Transcript.ToolCalls) -> Bool {
        a.id == b.id && a.calls == b.calls
      }

      /// The identifier type for a tool calls collection.
      public typealias ID = String
    }
  }

  @available(iOS 26.0, macOS 26.0, visionOS 26.0, watchOS 27.0, *)
  @available(tvOS, unavailable)
  extension Transcript.ToolCalls: RandomAccessCollection {
    /// Accesses the tool call at the specified position.
