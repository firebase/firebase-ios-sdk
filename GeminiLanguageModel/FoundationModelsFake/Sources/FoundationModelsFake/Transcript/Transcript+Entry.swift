#if compiler(>=6.4)
  extension Transcript {
    /// An individual record in a transcript.
    ///
    /// - SeeAlso: [`Transcript.Entry`](https://developer.apple.com/documentation/foundationmodels/transcript/entry)
    @nonexhaustive
    public enum Entry: Sendable, Identifiable, Equatable {
      /// System instructions or tool definitions provided to the model.
      case instructions(Transcript.Instructions)

      /// A prompt submitted to the model.
      case prompt(Transcript.Prompt)

      /// One or more tool calls initiated by the model.
      case toolCalls(Transcript.ToolCalls)

      /// The output returned from a tool call.
      case toolOutput(Transcript.ToolOutput)

      /// A response generated by the model.
      case response(Transcript.Response)

      /// The reasoning process produced by the model.
      @available(iOS 27.0, macOS 27.0, visionOS 27.0, watchOS 27.0, *)
      @available(tvOS, unavailable)
      case reasoning(Transcript.Reasoning)

      #if compiler(>=6.4.2)
        /// An arbitrary data entry recorded in the transcript.
        @available(iOS 27.2, macOS 27.2, visionOS 27.2, watchOS 27.2, *)
        @available(tvOS, unavailable)
        case data(Transcript.DataEntry)
      #endif  // compiler(>=6.4.2)

      /// The identifier type for a transcript entry.
      public typealias ID = String
    }
  }

  extension Transcript.Entry {
    /// The unique identifier of the entry.
    public var id: String {
      switch self {
      case .instructions(let instructions):
        instructions.id
      case .prompt(let prompt):
        prompt.id
      case .toolCalls(let toolCalls):
        toolCalls.id
      case .toolOutput(let toolOutput):
        toolOutput.id
      case .response(let response):
        response.id
      case .reasoning(let reasoning):
        reasoning.id
      #if compiler(>=6.4.2)
        case .data(let data):
          data.id
      #endif  // compiler(>=6.4.2)
      }
    }
  }

  extension Transcript.Entry {
    /// Returns a Boolean value indicating whether two transcript entries are equal.
    ///
    /// - Parameters:
    ///   - a: The first entry to compare.
    ///   - b: The second entry to compare.
    /// - Returns: `true` if both entries are equal.
    public static func == (a: Transcript.Entry, b: Transcript.Entry) -> Bool {
      switch (a, b) {
      case (.instructions(let a), .instructions(let b)):
        a == b
      case (.prompt(let a), .prompt(let b)):
        a == b
      case (.toolCalls(let a), .toolCalls(let b)):
        a == b
      case (.toolOutput(let a), .toolOutput(let b)):
        a == b
      case (.response(let a), .response(let b)):
        a == b
      case (.reasoning(let a), .reasoning(let b)):
        a == b
      #if compiler(>=6.4.2)
        case (.data(let a), .data(let b)):
          a == b
      #endif  // compiler(>=6.4.2)
      default:
        false
      }
    }
  }
#endif  // compiler(>=6.4)
