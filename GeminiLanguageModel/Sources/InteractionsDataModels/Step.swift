package import GeminiSharedDataModels

/// A step in the interaction.
package enum Step: Codable, Sendable, Equatable, Hashable {

  /// Code execution call step.
  case codeExecutionCallStep(CodeExecutionCallStep)

  /// Code execution result step.
  case codeExecutionResultStep(CodeExecutionResultStep)

  /// File Search call step.
  case fileSearchCallStep(FileSearchCallStep)

  /// File Search result step.
  case fileSearchResultStep(FileSearchResultStep)

  /// A function tool call step.
  case functionCallStep(FunctionCallStep)

  /// Result of a function tool call.
  case functionResultStep(FunctionResultStep)

  /// Google Maps call step.
  case googleMapsCallStep(GoogleMapsCallStep)

  /// Google Maps result step.
  case googleMapsResultStep(GoogleMapsResultStep)

  /// Google Search call step.
  case googleSearchCallStep(GoogleSearchCallStep)

  /// Google Search result step.
  case googleSearchResultStep(GoogleSearchResultStep)

  /// MCPServer tool call step.
  case mCPServerToolCallStep(MCPServerToolCallStep)

  /// MCPServer tool result step.
  case mCPServerToolResultStep(MCPServerToolResultStep)

  /// Output generated by the model.
  case modelOutputStep(ModelOutputStep)

  /// A server-initiated processing step for media analysis (e.g. video
  /// understanding).
  case processingCallStep(ProcessingCallStep)

  /// The result of a server-initiated media processing step.
  case processingResultStep(ProcessingResultStep)

  /// A thought step.
  case thoughtStep(ThoughtStep)

  /// URL context call step.
  case uRLContextCallStep(URLContextCallStep)

  /// URL context result step.
  case uRLContextResultStep(URLContextResultStep)

  /// Input provided by the user.
  case userInputStep(UserInputStep)

  /// Unrecognized case.
  case unrecognized(JSONValue)

  private enum CodingKeys: String, CodingKey {
    case discriminator = "type"
  }

  package init(from decoder: any Decoder) throws {
    let container = try decoder.container(keyedBy: CodingKeys.self)
    let discValue = try container.decode(String.self, forKey: .discriminator)
    switch discValue {
    case "code_execution_call":
      let val = try CodeExecutionCallStep(from: decoder)
      self = .codeExecutionCallStep(val)
    case "code_execution_result":
      let val = try CodeExecutionResultStep(from: decoder)
      self = .codeExecutionResultStep(val)
    case "file_search_call":
      let val = try FileSearchCallStep(from: decoder)
      self = .fileSearchCallStep(val)
    case "file_search_result":
      let val = try FileSearchResultStep(from: decoder)
      self = .fileSearchResultStep(val)
    case "function_call":
      let val = try FunctionCallStep(from: decoder)
      self = .functionCallStep(val)
    case "function_result":
      let val = try FunctionResultStep(from: decoder)
      self = .functionResultStep(val)
    case "google_maps_call":
      let val = try GoogleMapsCallStep(from: decoder)
      self = .googleMapsCallStep(val)
    case "google_maps_result":
      let val = try GoogleMapsResultStep(from: decoder)
      self = .googleMapsResultStep(val)
    case "google_search_call":
      let val = try GoogleSearchCallStep(from: decoder)
      self = .googleSearchCallStep(val)
    case "google_search_result":
      let val = try GoogleSearchResultStep(from: decoder)
      self = .googleSearchResultStep(val)
    case "mcp_server_tool_call":
      let val = try MCPServerToolCallStep(from: decoder)
      self = .mCPServerToolCallStep(val)
    case "mcp_server_tool_result":
      let val = try MCPServerToolResultStep(from: decoder)
      self = .mCPServerToolResultStep(val)
    case "model_output":
      let val = try ModelOutputStep(from: decoder)
      self = .modelOutputStep(val)
    case "processing_call":
      let val = try ProcessingCallStep(from: decoder)
      self = .processingCallStep(val)
    case "processing_result":
      let val = try ProcessingResultStep(from: decoder)
      self = .processingResultStep(val)
    case "thought":
      let val = try ThoughtStep(from: decoder)
      self = .thoughtStep(val)
    case "url_context_call":
      let val = try URLContextCallStep(from: decoder)
      self = .uRLContextCallStep(val)
    case "url_context_result":
      let val = try URLContextResultStep(from: decoder)
      self = .uRLContextResultStep(val)
    case "user_input":
      let val = try UserInputStep(from: decoder)
      self = .userInputStep(val)
    default:
      let val = try JSONValue(from: decoder)
      self = .unrecognized(val)
    }
  }

  package func encode(to encoder: any Encoder) throws {
    switch self {
    case .codeExecutionCallStep(let val):
      try val.encode(to: encoder)
    case .codeExecutionResultStep(let val):
      try val.encode(to: encoder)
    case .fileSearchCallStep(let val):
      try val.encode(to: encoder)
    case .fileSearchResultStep(let val):
      try val.encode(to: encoder)
    case .functionCallStep(let val):
      try val.encode(to: encoder)
    case .functionResultStep(let val):
      try val.encode(to: encoder)
    case .googleMapsCallStep(let val):
      try val.encode(to: encoder)
    case .googleMapsResultStep(let val):
      try val.encode(to: encoder)
    case .googleSearchCallStep(let val):
      try val.encode(to: encoder)
    case .googleSearchResultStep(let val):
      try val.encode(to: encoder)
    case .mCPServerToolCallStep(let val):
      try val.encode(to: encoder)
    case .mCPServerToolResultStep(let val):
      try val.encode(to: encoder)
    case .modelOutputStep(let val):
      try val.encode(to: encoder)
    case .processingCallStep(let val):
      try val.encode(to: encoder)
    case .processingResultStep(let val):
      try val.encode(to: encoder)
    case .thoughtStep(let val):
      try val.encode(to: encoder)
    case .uRLContextCallStep(let val):
      try val.encode(to: encoder)
    case .uRLContextResultStep(let val):
      try val.encode(to: encoder)
    case .userInputStep(let val):
      try val.encode(to: encoder)
    case .unrecognized(let val):
      try val.encode(to: encoder)
    }
  }
}
