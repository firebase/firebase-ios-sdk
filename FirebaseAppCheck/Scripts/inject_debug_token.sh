# Generates AppCheckDebugToken.generated.swift, which embeds the Firebase App
# Check debug token for the app in Debug builds, from an Xcode Run Script build
# phase. Prefer FirebaseAppCheckDebugTokenPlugin where possible, and keep the
# generation logic in sync with
# FirebaseAppCheck/Plugins/DebugTokenPlugin/plugin.swift. See
# FirebaseAppCheck/Plugins/DebugTokenPlugin/README.md.
#
# Usage:
#   inject_debug_token.sh [output_swift_file] [google_service_info_plist]
#
# Environment:
#   FIREBASE_APPCHECK_CONFIG_PATH  Overrides the Firebase CLI configuration file.

set -eu

output_file="${1:-${SCRIPT_OUTPUT_FILE_0:-${DERIVED_FILE_DIR:-.}/AppCheckDebugToken.generated.swift}}"
plist_path="${2:-${GOOGLE_SERVICE_INFO_PLIST:-}}"

PATH=/usr/bin:/bin:/usr/sbin:/sbin
export PATH

# Writes the generated file with the given token for the given app ID (or no
# token if either is empty). The file is rewritten only when its contents
# change to avoid unnecessary recompilation.
write_output() {
  if [ -n "$1" ] && [ -n "$2" ]; then
    tokens="[\"$1\": \"$2\"]"
  else
    tokens="[:]"
  fi
  mkdir -p "$(dirname "$output_file")"
  tmp_file="$output_file.tmp"
  cat > "$tmp_file" <<EOF
// Generated by FirebaseAppCheck/Scripts/inject_debug_token.sh. Do not edit or commit this file.
import Foundation

#if DEBUG
  @objc(FIRAppCheckInjectedDebugToken)
  public final class FIRAppCheckInjectedDebugToken: NSObject {
    @objc public static let tokens: [String: String] = $tokens
  }
#endif
EOF
  if [ -f "$output_file" ] && cmp -s "$tmp_file" "$output_file"; then
    rm -f "$tmp_file"
  else
    mv -f "$tmp_file" "$output_file"
  fi
}

# Never embed a debug token in non-Debug build configurations.
case "${CONFIGURATION:-Debug}" in
  *Debug* | *debug* | *DEBUG*) ;;
  *)
    write_output "" ""
    exit 0
    ;;
esac

# Match the Firebase CLI's configstore location: $XDG_CONFIG_HOME/configstore
# when XDG_CONFIG_HOME is set, otherwise ~/.config/configstore.
config_file="${FIREBASE_APPCHECK_CONFIG_PATH:-}"
if [ -z "$config_file" ]; then
  for candidate in \
    "${XDG_CONFIG_HOME:+$XDG_CONFIG_HOME/configstore/firebase-appcheck.json}" \
    "${HOME:+$HOME/.config/configstore/firebase-appcheck.json}"; do
    if [ -n "$candidate" ] && [ -f "$candidate" ]; then
      config_file="$candidate"
      break
    fi
  done
fi

if [ -z "$config_file" ] || [ ! -f "$config_file" ]; then
  write_output "" ""
  exit 0
fi

# Locate GoogleService-Info.plist if not explicitly provided.
if [ -z "$plist_path" ] || [ ! -f "$plist_path" ]; then
  for candidate in \
    "${BUILT_PRODUCTS_DIR:-}/${UNLOCALIZED_RESOURCES_FOLDER_PATH:-}/GoogleService-Info.plist" \
    "${PROJECT_DIR:-}/GoogleService-Info.plist" \
    "${SRCROOT:-}/GoogleService-Info.plist"; do
    if [ -f "$candidate" ]; then
      plist_path="$candidate"
      break
    fi
  done
fi

app_id="${FIREBASE_GOOGLE_APP_ID:-}"
if [ -z "$app_id" ] && [ -n "$plist_path" ] && [ -f "$plist_path" ]; then
  app_id="$(plutil -extract GOOGLE_APP_ID raw -o - "$plist_path" 2>/dev/null || true)"
fi
if [ -z "$app_id" ]; then
  echo "warning: inject_debug_token.sh: GOOGLE_APP_ID not found; no debug token embedded." >&2
  write_output "" ""
  exit 0
fi

token=""
case "$app_id" in
  *[!0-9A-Za-z:_-]*)
    echo "warning: inject_debug_token.sh: unexpected GOOGLE_APP_ID format." >&2
    ;;
  *)
    token="$(plutil -extract "tokens.$app_id" raw -o - "$config_file" 2>/dev/null || true)"
    ;;
esac
# Only accept characters that can't break out of the generated Swift string
# literal.
case "$token" in
  *[!0-9A-Za-z._~-]*)
    echo "warning: inject_debug_token.sh: ignoring malformed debug token." >&2
    token=""
    ;;
esac
if [ -z "$token" ]; then
  echo "note: inject_debug_token.sh: no debug token for $app_id in $config_file." >&2
fi

write_output "$app_id" "$token"
